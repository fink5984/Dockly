/**
 * Local development environment — never touches production.
 *
 *   npm run dev:setup     create/start a private Postgres under .data/pg (port 54330),
 *                         apply migrations, seed a demo workspace, write .env.local
 *   npm run dev:db:stop   stop that Postgres
 *
 * Requires PostgreSQL binaries (initdb, pg_ctl) on PATH.
 * Demo login: demo@dockly.local / dockly-demo-123
 */
import { execFileSync } from 'child_process'
import { existsSync, writeFileSync, mkdirSync, readFileSync } from 'fs'
import { randomBytes } from 'crypto'
import { resolve } from 'path'
import pg from 'pg'

const ROOT = resolve(import.meta.dirname, '..')
const DATA = resolve(ROOT, '.data')
const PGDATA = resolve(DATA, 'pg')
const PORT = 54330
const DB = 'dockly_dev'
const ADMIN_URL = `postgresql://postgres@127.0.0.1:${PORT}/postgres`
const DB_URL = `postgresql://postgres@127.0.0.1:${PORT}/${DB}`

const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: 'pipe', ...opts }).toString()

if (process.argv.includes('--stop')) {
  try { run('pg_ctl', ['-D', PGDATA, 'stop', '-m', 'fast']); console.log('Postgres stopped') } catch { console.log('Postgres was not running') }
  process.exit(0)
}

mkdirSync(DATA, { recursive: true })
if (!existsSync(resolve(PGDATA, 'PG_VERSION'))) {
  console.log('• Initialising local Postgres in .data/pg')
  run('initdb', ['-D', PGDATA, '-U', 'postgres', '-A', 'trust', '-E', 'UTF8', '--locale=C'])
}
try {
  run('pg_ctl', ['-D', PGDATA, 'status'])
} catch {
  console.log(`• Starting Postgres on port ${PORT}`)
  // stdio ignored: the postmaster inherits pipes and would keep execFileSync waiting forever.
  execFileSync('pg_ctl', ['-D', PGDATA, '-o', `-p ${PORT} -c listen_addresses=127.0.0.1`, '-l', resolve(DATA, 'pg.log'), '-w', 'start'], { stdio: 'ignore' })
}

const admin = new pg.Client({ connectionString: ADMIN_URL })
await admin.connect()
const exists = await admin.query('SELECT 1 FROM pg_database WHERE datname = $1', [DB])
if (!exists.rowCount) {
  await admin.query(`CREATE DATABASE ${DB}`)
  console.log(`• Created database ${DB}`)
}
await admin.end()

// .env.local (git-ignored) — the server loads it before .env
const envPath = resolve(ROOT, '.env.local')
let secret = randomBytes(48).toString('base64url')
if (existsSync(envPath)) {
  const m = /SESSION_SECRET=(.+)/.exec(readFileSync(envPath, 'utf8'))
  if (m) secret = m[1].trim()
}
writeFileSync(envPath, [
  '# Local development (generated by scripts/dev-setup.mjs). Never commit.',
  `DATABASE_URL=${DB_URL}`,
  'DATABASE_SSL=false',
  '# API port for local dev (Vite proxies /api here). 3001 is often taken by other projects.',
  'PORT=3101',
  `SESSION_SECRET=${secret}`,
  'APP_BASE_URL=http://localhost:5173',
  'STORAGE_DRIVER=local',
  'LOCAL_STORAGE_DIR=.data/storage',
  'WHATSAPP_MODE=log',
  'WHATSAPP_VERIFY_TOKEN=local-verify-token',
  'WHATSAPP_APP_SECRET=local-app-secret',
  'AUTOMATION_ENABLED=true',
  '',
].join('\n'))
console.log('• Wrote .env.local')

process.env.DATABASE_URL = DB_URL
process.env.DATABASE_SSL = 'false'
process.env.SESSION_SECRET = secret
process.env.STORAGE_DRIVER = 'local'
process.env.LOCAL_STORAGE_DIR = resolve(DATA, 'storage')

const { runMigrations } = await import('../server/db/migrate.mjs')
await runMigrations({ connectionString: DB_URL, ssl: false })

const { seedDemo } = await import('./seed-demo.mjs')
await seedDemo()
console.log('\n✔ Ready. In two terminals run:\n    npm run dev:server\n    npm run dev\n  then open http://localhost:5173 and sign in with demo@dockly.local / dockly-demo-123')
process.exit(0)
